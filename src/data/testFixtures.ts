import type { Appliance, Category, SlotId } from "../types";

/**
 * Synthetic appliances for the rule and fit tests.
 *
 * These deliberately do not come from `data/appliances.json`. That file is
 * re-imported from the inventory sheet whenever stock changes, so a test keyed
 * to a model in it fails the day that model sells out — which says nothing
 * about the rule under test. Invariants that *should* track live data live in
 * `catalogue.test.ts` instead.
 */
export function appliance(overrides: Partial<Appliance> & { id: string }): Appliance {
  return {
    slot: "slot-range" as SlotId,
    category: "range" as Category,
    brand: "Test",
    model: overrides.id.toUpperCase(),
    series: null,
    msrpUSD: 1000,
    sourceUrl: "https://example.com/",
    verifiedAt: null,
    installType: ["slide-in"],
    fuel: null,
    blower: null,
    compatibleBlowers: [],
    topDepthIn: null,
    widthIn: 36,
    heightIn: 36,
    depthIn: 24,
    cutoutWidthIn: 36,
    cutoutHeightIn: 36,
    cutoutDepthIn: 24,
    finish: ["stainless"],
    leadTimeWeeks: 4,
    highlights: { en: [], zh: [] },
    imageUrl: null,
    ...overrides,
    requires: {
      voltage: 120,
      amps: 15,
      gasBTU: null,
      water: false,
      cfm: null,
      makeupAirRequired: false,
      ...overrides.requires,
    },
  };
}

